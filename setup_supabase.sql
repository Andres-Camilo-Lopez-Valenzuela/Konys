-- 1. ELIMINAR TABLAS PREVIAS SI EXISTEN (Para inicio limpio)
DROP TABLE IF EXISTS public.reservas CASCADE;
DROP TABLE IF EXISTS public.horarios CASCADE;
DROP TABLE IF EXISTS public.mesas CASCADE;

-- 2. TABLA: MESAS
CREATE TABLE public.mesas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    zona VARCHAR(50) NOT NULL DEFAULT 'Salón Principal',
    capacidad INT NOT NULL CHECK (capacidad > 0),
    activa BOOLEAN NOT NULL DEFAULT true,
    foto_url TEXT,
    creado_en TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABLA: HORARIOS
CREATE TABLE public.horarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_semana VARCHAR(20) DEFAULT 'todos',
    jornada VARCHAR(50) NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    duracion_slot INT NOT NULL DEFAULT 60,
    activo BOOLEAN NOT NULL DEFAULT true
);

-- 4. TABLA: RESERVAS
CREATE TABLE public.reservas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mesa_id BIGINT REFERENCES public.mesas(id) ON DELETE RESTRICT NOT NULL,
    cliente_nombre VARCHAR(150) NOT NULL,
    cliente_contacto VARCHAR(100) NOT NULL,
    num_personas INT NOT NULL CHECK (num_personas > 0),
    fecha DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'confirmada' CHECK (estado IN ('confirmada', 'cancelada', 'completada')),
    creado_en TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. HABILITAR ROW LEVEL SECURITY (RLS)
ALTER TABLE public.mesas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.horarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reservas ENABLE ROW LEVEL SECURITY;

-- 6. POLÍTICAS DE ACCESO PÚBLICO (ANON KEY - JAMSTACK CLIENT)
-- Mesas: cualquiera puede consultar; el panel admin puede insertar y actualizar
CREATE POLICY "Permitir lectura de mesas" ON public.mesas FOR SELECT USING (true);
CREATE POLICY "Permitir gestión de mesas" ON public.mesas FOR ALL USING (true);

-- Horarios: cualquiera puede consultar los turnos activos; gestión libre
CREATE POLICY "Permitir lectura de horarios" ON public.horarios FOR SELECT USING (true);
CREATE POLICY "Permitir gestión de horarios" ON public.horarios FOR ALL USING (true);

-- Reservas: cualquiera puede consultar disponibilidad y registrar reservas
CREATE POLICY "Permitir lectura de reservas" ON public.reservas FOR SELECT USING (true);
CREATE POLICY "Permitir crear reservas" ON public.reservas FOR INSERT WITH CHECK (true);
CREATE POLICY "Permitir actualizar reservas" ON public.reservas FOR UPDATE USING (true);

